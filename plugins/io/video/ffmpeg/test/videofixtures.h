// GENERATED test fixtures — tiny video clips with known contents. Video cannot be hand-built like
// a PNG, and the prebuilt FFmpeg is --disable-avdevice, so there is no lavfi/testsrc to draw from:
// the frames are written as raw RGB24 by the python snippet below and piped through the encoder.
//
// Each frame is a FLAT colour (r = 20*n + 10, g = 128, b = 250 - 20*n) with a white block that
// moves 4px per frame. Flat is deliberate — these are lossy codecs, so a per-frame identity that
// survives encoding has to be a large uniform area rather than a marker pixel.
//
//   python3 - <<'EOF'
//   w, h, n = 64, 48, 12
//   with open('frames.raw', 'wb') as f:
//       for i in range(n):
//           buf = bytearray()
//           for y in range(h):
//               for x in range(w):
//                   block = abs(x - (4 + i * 4)) < 6 and abs(y - 24) < 6
