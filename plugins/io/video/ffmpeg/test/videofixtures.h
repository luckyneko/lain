//           f.write(buf)
//   EOF
//   R="-f rawvideo -pix_fmt rgb24 -s 64x48 -r 24 -i frames.raw"
//   ffmpeg $R -c:v h264_videotoolbox -g 4 -b:v 200k -pix_fmt yuv420p clip.mp4
//   ffmpeg $R -c:v mpeg4 -bf 2 -g 6 -q:v 4 -pix_fmt yuv420p bframes.mp4
